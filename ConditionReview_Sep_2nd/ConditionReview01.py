# 복습 문제 (조건문)

# [1번 문제]
# 입력받은 수를 출력하고 그 수가 10보다 크면 
# 다음 줄에 "10보다 큰 수를 입력하셨습니다."라는 메시지를 출력하는 코드 짜기

# 1. 입력 받은 정수를 저장할 변수 선언
# 2. 입력을 받으려면 입력기 - input()
# 3. 숫자 Type으로 형변환(캐스팅)
number = int(input("정수를 입력하시오> "))

# 4. 입력받은 수를 출력 - print()
print(number)

# 5. 입력받은 수와 10을 비교해서, 만약 입력 값이 10보다 크다면
# 6. 출력 - "10보다 큰 값을 입력하셨습니다."
if number > 10:
    print("10보다 큰 값을 입력하셨습니다.")





